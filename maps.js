function cloneGrid(grid) {
    return grid.map((row) => row.slice());
}

function mirrorGridH(grid) {
    const w = grid[0].length;
    return grid.map((row) => {
        const nr = [];
        for (let j = 0; j < w; j++) nr.push(row[w - 1 - j]);
        return nr;
    });
}

function mirrorGridV(grid) {
    return grid.map((_, i) => grid[grid.length - 1 - i].slice());
}

function rotateGrid180(grid) {
    return mirrorGridH(mirrorGridV(cloneGrid(grid)));
}

function cloneAndPatch(grid, patches) {
    const g = cloneGrid(grid);
    for (const [r, c, v] of patches) {
        if (r >= 0 && r < g.length && c >= 0 && c < g[0].length) g[r][c] = v;
    }
    return g;
}

